-- Generic knowledge base: entries, questions, quote-backed steps, learned
-- product terms, categories as data, and the ingester's sources, runs,
-- documents and chunks (SQLite twin: backend/db.py SCHEMA).
-- The e-commerce orders mock table goes: Sahayak has no order lookup.
DROP TABLE IF EXISTS orders;
CREATE TABLE kb_categories (
    name         TEXT PRIMARY KEY,
    label        TEXT NOT NULL,
    description  TEXT NOT NULL DEFAULT '',
    status       TEXT NOT NULL DEFAULT 'confirmed',
    source       TEXT NOT NULL DEFAULT 'staff',
    created_at   TIMESTAMPTZ NOT NULL,
    confirmed_by TEXT,
    confirmed_at TIMESTAMPTZ
);

-- Where KB content comes from. public_confirmed_*: who confirmed the
-- content is public or allowed to be used, and when (required).
CREATE TABLE kb_sources (
    source_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                TEXT NOT NULL,
    name                TEXT NOT NULL,
    root_url            TEXT,
    config              TEXT NOT NULL DEFAULT '{}',
    public_confirmed_by TEXT NOT NULL,
    public_confirmed_at TIMESTAMPTZ NOT NULL,
    active              INTEGER NOT NULL DEFAULT 1,
    created_by          TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL
);

-- One ingestion run of a source. Model calls are estimated before the run
-- starts and capped per run (model_call_cap) and per day; a run that hits
-- a cap stops with stop_reason set. errors: counts by reason code only.
CREATE TABLE kb_ingest_runs (
    run_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id             BIGINT NOT NULL REFERENCES kb_sources(source_id),
    status                TEXT NOT NULL,
    triggered_by          TEXT NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL,
    started_at            TIMESTAMPTZ,
    finished_at           TIMESTAMPTZ,
    estimated_model_calls INTEGER NOT NULL DEFAULT 0,
    model_call_cap        INTEGER NOT NULL,
    model_calls           INTEGER NOT NULL DEFAULT 0,
    stop_reason           TEXT,
    pages_fetched         INTEGER NOT NULL DEFAULT 0,
    pages_unchanged       INTEGER NOT NULL DEFAULT 0,
    pages_skipped         INTEGER NOT NULL DEFAULT 0,
    chunks                INTEGER NOT NULL DEFAULT 0,
    drafts_created        INTEGER NOT NULL DEFAULT 0,
    steps_rejected        INTEGER NOT NULL DEFAULT 0,
    errors                TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX idx_kb_runs_source ON kb_ingest_runs(source_id, created_at);

-- A fetched page or file. Only its hash is kept, never the page itself.
CREATE TABLE kb_documents (
    document_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     BIGINT NOT NULL REFERENCES kb_sources(source_id),
    location      TEXT NOT NULL,
    title         TEXT,
    content_hash  TEXT,
    http_status   INTEGER,
    etag          TEXT,
    last_modified TEXT,
    byte_size     INTEGER,
    state         TEXT NOT NULL,
    miss_count    INTEGER NOT NULL DEFAULT 0,
    fetched_at    TIMESTAMPTZ,
    UNIQUE (source_id, location)
);

-- A heading section of a document. text is purged (purged_at) once every
-- draft from it is decided, or after the retention period.
CREATE TABLE kb_chunks (
    chunk_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id       BIGINT NOT NULL REFERENCES kb_documents(document_id) ON DELETE CASCADE,
    run_id            BIGINT REFERENCES kb_ingest_runs(run_id),
    ordinal           INTEGER NOT NULL,
    heading_path      TEXT NOT NULL DEFAULT '',
    text              TEXT,
    chunk_hash        TEXT NOT NULL,
    char_start        INTEGER,
    char_end          INTEGER,
    flagged_injection INTEGER NOT NULL DEFAULT 0,
    purged_at         TIMESTAMPTZ
);
CREATE INDEX idx_kb_chunks_document ON kb_chunks(document_id);

CREATE TABLE kb_entries (
    kb_entry_id     TEXT PRIMARY KEY,
    status          TEXT NOT NULL,
    title           TEXT NOT NULL,
    answer          TEXT NOT NULL DEFAULT '',
    kind            TEXT,
    handling        TEXT NOT NULL DEFAULT 'answer',
    collect         TEXT NOT NULL DEFAULT '[]',
    category        TEXT NOT NULL,
    source_url      TEXT,
    document_id     BIGINT REFERENCES kb_documents(document_id) ON DELETE SET NULL,
    chunk_id        BIGINT REFERENCES kb_chunks(chunk_id) ON DELETE SET NULL,
    chunk_hash      TEXT,
    run_id          BIGINT REFERENCES kb_ingest_runs(run_id),
    stale           INTEGER NOT NULL DEFAULT 0,
    supersedes      TEXT,
    duplicate_of    TEXT,
    duplicate_score DOUBLE PRECISION,
    created_by      TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_by      TEXT,
    updated_at      TIMESTAMPTZ NOT NULL,
    reviewed_by     TEXT,
    reviewed_at     TIMESTAMPTZ,
    review_note     TEXT,
    version         INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX idx_kb_entries_status ON kb_entries(status);

CREATE TABLE kb_entry_questions (
    entry_id TEXT NOT NULL REFERENCES kb_entries(kb_entry_id) ON DELETE CASCADE,
    ordinal  INTEGER NOT NULL,
    text     TEXT NOT NULL,
    PRIMARY KEY (entry_id, ordinal)
);

-- quote: the passage of the entry's chunk the step is backed by.
-- support_check: the second model check's verdict ("supported"), NULL
-- for steps written by staff.
CREATE TABLE kb_entry_steps (
    entry_id      TEXT NOT NULL REFERENCES kb_entries(kb_entry_id) ON DELETE CASCADE,
    ordinal       INTEGER NOT NULL,
    text          TEXT NOT NULL,
    quote         TEXT NOT NULL,
    quote_offset  INTEGER,
    support_check TEXT,
    PRIMARY KEY (entry_id, ordinal)
);

-- Product terms learned from the content: proposed by the ingester (or
-- staff), confirmed by a reviewer. pattern is built from label + aliases.
CREATE TABLE kb_terms (
    term_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label             TEXT NOT NULL,
    kind              TEXT NOT NULL,
    aliases           TEXT NOT NULL DEFAULT '[]',
    pattern           TEXT NOT NULL,
    status            TEXT NOT NULL,
    merged_into       BIGINT REFERENCES kb_terms(term_id),
    evidence_quote    TEXT,
    evidence_chunk_id BIGINT REFERENCES kb_chunks(chunk_id) ON DELETE SET NULL,
    evidence_count    INTEGER NOT NULL DEFAULT 0,
    proposed_by       TEXT NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL,
    confirmed_by      TEXT,
    confirmed_at      TIMESTAMPTZ
);
CREATE UNIQUE INDEX idx_kb_terms_label ON kb_terms(lower(label));

CREATE TABLE kb_entry_terms (
    entry_id TEXT NOT NULL REFERENCES kb_entries(kb_entry_id) ON DELETE CASCADE,
    term_id  BIGINT NOT NULL REFERENCES kb_terms(term_id) ON DELETE CASCADE,
    PRIMARY KEY (entry_id, term_id)
);
